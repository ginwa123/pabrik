// tools/codegen_webapp_assets.zig Comptime codegen: walk the Vue webapp's
// built dist/ tree and emit a Zig source file with the byte-for-byte contents
// of every asset embedded as string literals.

const std = @import("std");
const builtin = @import("builtin");

pub fn main(init: std.process.Init) !void {
    // Codegen is a one-shot CLI tool: each invocation scans dist/ once and
    // writes one output file. Page allocator is fine here — no leak
    // concerns for a process that exits within a few hundred ms.
    const allocator = std.heap.page_allocator;

    // CLI args. The build.zig step invokes the binary with two positional
    // arguments: the dist/ root and the output .zig file path.
    var args_iter = try std.process.Args.Iterator.initAllocator(init.minimal.args, allocator);
    _ = args_iter.next() orelse return error.MissingExeName;
    const dist_path = args_iter.next() orelse return error.MissingDistPath;
    const out_path = args_iter.next() orelse return error.MissingOutPath;

    // Check if dist_path exists.
    var dist_path_buf: [8192:0]u8 = undefined;
    const dist_path_z = copyToNull(&dist_path_buf, dist_path);
    const acc_rc = std.c.access(dist_path_z, 0); // F_OK = 0
    const dist_exists = if (acc_rc == 0) true else blk: {
        const errno_val = std.c.errno(acc_rc);
        if (errno_val == .NOENT) break :blk false;
        return error.AccessFailed;
    };
    if (!dist_exists) {
        std.debug.print("warning: {s} not found; emitting empty webapp_assets.zig stub. Run 'bun run build' in the webapp dir to populate.\n", .{dist_path});
    }

    // Walk the dist/ tree and collect every file's path (relative to
    // the root, with forward slashes — the walker normalizes them).
    var files: std.ArrayList([]const u8) = .empty;
    defer files.deinit(allocator);
    if (dist_exists) {
        try walkDir(allocator, dist_path, "", &files);
    }

    // Deterministic output order: sort lexicographically.
    std.mem.sort([]const u8, files.items, {}, lessThan);

    // Accumulate the generated Zig source in a heap ArrayList. The
    // dist/ is ~4.5 MiB, the generated source is ~10 MiB after hex
    // escaping.
    var out_buf: std.ArrayList(u8) = .empty;
    defer out_buf.deinit(allocator);

    // Header — the generated file's public surface. Keep this stable;
    // the extraction.zig code imports `webapp_assets.assets` and treats
    // each `Asset` as a `{ path, content, mime }` triple.
    try out_buf.appendSlice(allocator,
        \\// GENERATED by tools/codegen_webapp_assets.zig — DO NOT EDIT
        \\// To regenerate: zig build codegen:webapp-assets
        \\
        \\const std = @import("std");
        \\
        \\pub const Asset = struct {
        \\    /// Path as served by the webserver, e.g. "/assets/index-abc.js"
        \\    path: []const u8,
        \\    /// File contents (use as-is; do not modify).
        \\    content: []const u8,
        \\    /// Inferred MIME type with charset for text/* types.
        \\    mime: []const u8,
        \\};
        \\
    );

    try out_buf.appendSlice(allocator, "pub const assets: []const Asset = &.{\n");

    for (files.items) |rel| {
        const abs = try std.fs.path.join(allocator, &.{ dist_path, rel });
        defer allocator.free(abs);
        const content = try readFileAll(allocator, abs, 10 * 1024 * 1024);
        defer allocator.free(content);
        const path_served = try std.fmt.allocPrint(allocator, "/{s}", .{rel});
        defer allocator.free(path_served);
        const mime = inferMime(rel);

        const header_line = try std.fmt.allocPrint(
            allocator,
            "    .{{ .path = \"{s}\", .content = \"",
            .{path_served},
        );
        defer allocator.free(header_line);
        try out_buf.appendSlice(allocator, header_line);

        for (content) |b| {
            switch (b) {
                0...8, 11, 12, 14...31 => {
                    var esc: [4]u8 = undefined;
                    _ = std.fmt.bufPrint(&esc, "\\x{x:0>2}", .{b}) catch @panic("codegen: bufPrint of the hex escape failed");
                    try out_buf.appendSlice(allocator, &esc);
                },
                32...33, 35...91, 93...126 => try out_buf.append(allocator, b),
                '"', '\\' => {
                    var esc: [2]u8 = .{ '\\', b };
                    try out_buf.appendSlice(allocator, &esc);
                },
                else => {
                    var esc: [4]u8 = undefined;
                    _ = std.fmt.bufPrint(&esc, "\\x{x:0>2}", .{b}) catch @panic("codegen: bufPrint of the hex escape failed");
                    try out_buf.appendSlice(allocator, &esc);
                },
            }
        }

        const footer_line = try std.fmt.allocPrint(allocator, "\", .mime = \"{s}\" }},\n", .{mime});
        defer allocator.free(footer_line);
        try out_buf.appendSlice(allocator, footer_line);
    }

    try out_buf.appendSlice(allocator, "};\n");

    // Open the output file. The parent dir is created if missing so the
    // step works on a fresh checkout with no `embedded/` dir.
    const out_dir_path = std.fs.path.dirname(out_path) orelse ".";
    const out_basename = std.fs.path.basename(out_path);
    try mkdirsRecursive(out_dir_path);

    // Write the accumulated buffer to disk.
    if (builtin.os.tag == .windows) {
        try writeAllWindows(out_path, out_buf.items);
    } else {
        const full_posix = try std.fs.path.join(std.heap.page_allocator, &.{ out_dir_path, out_basename });
        defer std.heap.page_allocator.free(full_posix);
        const out_fd = try openCreateTruncPosix(full_posix);
        defer _ = std.c.close(out_fd);
        var written: usize = 0;
        while (written < out_buf.items.len) {
            const n_rc = std.c.write(out_fd, out_buf.items[written..].ptr, out_buf.items.len - written);
            if (n_rc < 0) return error.WriteFailed;
            const n: usize = @intCast(n_rc);
            if (n == 0) return error.WriteFailed;
            written += n;
        }
    }

    if (dist_exists) {
        std.debug.print("Generated {s} with {d} assets\n", .{ out_path, files.items.len });
    } else {
        std.debug.print("Generated {s} with 0 assets (stub: dist/ was not found; run 'bun run build' to populate)\n", .{out_path});
    }
}

fn lessThan(_: void, a: []const u8, b: []const u8) bool {
    return std.mem.lessThan(u8, a, b);
}

/// Recursively walk a directory tree and append every regular file's path
/// (relative to `root`) to `out`. Directories are recursed; symlinks are
/// skipped to avoid cycles.
fn walkDir(
    allocator: std.mem.Allocator,
    root: []const u8,
    prefix: []const u8,
    out: *std.ArrayList([]const u8),
) !void {
    // `try switch (...) { ... }` propagates the error union returned by both
    // branches. (`switch` is a non-void expression here, so the function
    // body's trailing value needs `try`-ing when the inner returns `!T`.)
    return switch (builtin.os.tag) {
        .windows => walkDirWindows(allocator, root, prefix, out),
        else => walkDirPosix(allocator, root, prefix, out),
    };
}

fn walkDirPosix(
    allocator: std.mem.Allocator,
    root: []const u8,
    prefix: []const u8,
    out: *std.ArrayList([]const u8),
) !void {
    const full_dir = if (prefix.len == 0)
        try allocator.dupe(u8, root)
    else
        try std.fs.path.join(allocator, &.{ root, prefix });
    defer allocator.free(full_dir);

    var open_path_buf: [8192:0]u8 = undefined;
    const open_path = copyToNull(&open_path_buf, full_dir);
    const dir_ptr = std.c.opendir(open_path) orelse return error.OpenDirFailed;
    defer _ = std.c.closedir(dir_ptr);

    while (std.c.readdir(dir_ptr)) |raw_entry| {
        const entry: *std.c.dirent = raw_entry;
        const name = std.mem.sliceTo(&entry.name, 0);

        if (name.len > 0 and !(name.len == 1 and name[0] == '.') and
            !(name.len == 2 and name[0] == '.' and name[1] == '.'))
        {
            // `std.fs.path.join` on Windows uses `\` as the separator, but
            // the generated Zig string literal needs forward slashes
            // (otherwise `"/assets\foo.js"` is an invalid escape sequence —
            const rel_raw = try std.fs.path.join(allocator, &.{ prefix, name });
            defer allocator.free(rel_raw);
            // Manual replace: copy + swap `\` to `/`. (Zig 0.16 has
            // no `dupeAndReplace` on Allocator, only on ArrayList.)
            const rel = try allocator.alloc(u8, rel_raw.len);
            for (rel_raw, 0..) |c, i| {
                rel[i] = if (c == '\\') '/' else c;
            }

            if (entry.type == comptime dtValue(.REG)) {
                try out.append(allocator, rel);
            } else if (entry.type == comptime dtValue(.DIR)) {
                try walkDirPosix(allocator, root, rel, out);
            } else {
                allocator.free(rel); // symlinks etc. — skip
            }
        }
    }
}

// Win32 directory walking — uses `FindFirstFileW`/`FindNextFileW` from
// kernel32.dll.
extern "kernel32" fn FindFirstFileW(
    lpFileName: [*:0]const u16,
    lpFindFileData: *WIN32_FIND_DATAW,
) callconv(.winapi) ?std.os.windows.HANDLE;
extern "kernel32" fn FindNextFileW(
    hFindFile: std.os.windows.HANDLE,
    lpFindFileData: *WIN32_FIND_DATAW,
) callconv(.winapi) std.os.windows.BOOL;
extern "kernel32" fn FindClose(
    hFindFile: std.os.windows.HANDLE,
) callconv(.winapi) std.os.windows.BOOL;

/// Win32's FIND_DATA structure.
const WIN32_FIND_DATAW = extern struct {
    dwFileAttributes: u32,
    ftCreationTime: std.os.windows.FILETIME,
    ftLastAccessTime: std.os.windows.FILETIME,
    ftLastWriteTime: std.os.windows.FILETIME,
    nFileSizeHigh: u32,
    nFileSizeLow: u32,
    dwReserved0: u32,
    dwReserved1: u32,
    cFileName: [std.os.windows.MAX_PATH]u16,
    // Trailing `cAlternateFileName` is intentionally omitted — Zig
    // 0.16 doesn't expose it, and we never use it.
};

fn walkDirWindows(
    allocator: std.mem.Allocator,
    root: []const u8,
    prefix: []const u8,
    out: *std.ArrayList([]const u8),
) !void {
    const full_dir = if (prefix.len == 0)
        try allocator.dupe(u8, root)
    else
        try std.fs.path.join(allocator, &.{ root, prefix });
    defer allocator.free(full_dir);

    // Convert the UTF-8 absolute path + an `\*` wildcard (Win32's
    // FindFirstFileW wants the search pattern to include a wildcard to
    // enumerate the directory itself) into a WTF-16 buffer.
    var full_w: [std.fs.max_path_bytes:0]u16 = undefined;
    // `wtf8ToWtf16Le` returns the count of `u16` units WRITTEN into
    // the destination buffer (`usize`), not a slice. Pre-allocate
    // room for the appended `\*` and trailing NUL.
    const written = std.unicode.wtf8ToWtf16Le(&full_w, full_dir) catch
        return error.OpenDirFailed;
    if (written + 3 > full_w.len) return error.OpenDirFailed; // `\*\0` + 1
    full_w[written] = '\\';
    full_w[written + 1] = '*';
    full_w[written + 2] = 0;

    var find_data: WIN32_FIND_DATAW = undefined;
    const h_opt = FindFirstFileW(@ptrCast(&full_w), &find_data);
    const h = h_opt orelse return error.OpenDirFailed;
    defer _ = FindClose(h);

    while (true) {
        // The file name is `cFileName` — NUL-terminated WTF-16,
        // up to MAX_PATH characters. Slice on first 0.
        const name_w = std.mem.sliceTo(&find_data.cFileName, 0);

        // Skip "." / ".." (FAT filesystem doesn't generate these
        // but a paranoid check costs nothing).
        const is_dot = name_w.len == 1 and name_w[0] == '.';
        const is_dotdot = name_w.len == 2 and
            name_w[0] == '.' and name_w[1] == '.';
        if (!is_dot and !is_dotdot) {
            // Convert WTF-16 back to UTF-8 to use in std.fs.path.join
            // (which is UTF-8 on every host) and to emit the relative
            // path that gets baked into the generated Zig source.
            const name_u8_len = std.unicode.calcWtf8Len(name_w);
            const name_buf = try allocator.alloc(u8, name_u8_len);
            defer allocator.free(name_buf);
            _ = std.unicode.wtf16LeToWtf8(name_buf, name_w);

            const rel_raw = try std.fs.path.join(
                allocator,
                &.{ prefix, name_buf },
            );
            defer allocator.free(rel_raw);
            // On Windows, `std.fs.path.join` produces backslash-separated
            // paths.
            const rel = try allocator.alloc(u8, rel_raw.len);
            for (rel_raw, 0..) |c, i| {
                rel[i] = if (c == '\\') '/' else c;
            }

            // `dwFileAttributes & FILE_ATTRIBUTE_DIRECTORY` is the
            // MS-DOS-era filesystem directory bit — stable across
            // every Win32-supported filesystem since Windows 95.
            const is_dir = (find_data.dwFileAttributes & 0x10) != 0;
            if (is_dir) {
                try walkDirWindows(allocator, root, rel, out);
            } else {
                try out.append(allocator, rel);
            }
        }

        const more = FindNextFileW(h, &find_data);
        if (more.toBool() == false) break;
    }
}

/// Return the integer `DT_*` value for `kind` (REG | DIR) on the current
/// platform.
fn dtValue(comptime kind: enum { REG, DIR }) u8 {
    return switch (kind) {
        .REG => 8, // DT_REG
        .DIR => 4, // DT_DIR
    };
}

/// Copy a path into a caller-provided NUL-terminated stack buffer and return
/// a pointer to the start.
fn copyToNull(buf: *[8192:0]u8, path: []const u8) [*:0]const u8 {
    if (path.len >= buf.len) @panic("path too long for null-terminated buffer");
    @memcpy(buf[0..path.len], path);
    buf[path.len] = 0;
    return buf;
}

/// `mkdir(2)` the given path, creating any missing parents.
fn mkdirsRecursive(path: []const u8) !void {
    if (path.len == 0 or (path.len == 1 and path[0] == '.')) return;

    var path_buf: [8192:0]u8 = undefined;
    const path_z = copyToNull(&path_buf, path);

    // If it already exists, we're done. std.c.access returns 0 on
    // success, -1 on failure (errno set to EEXIST or similar).
    if (std.c.access(path_z, 0) == 0) return;

    // Recurse on the parent first.
    if (std.fs.path.dirname(path)) |parent| {
        if (parent.len < path.len) try mkdirsRecursive(parent);
    }

    // Now mkdir this path. std.c.mkdir returns 0 on success, -1 on
    // failure with errno set. EEXIST is fine (a concurrent creator).
    if (std.c.mkdir(path_z, @as(std.c.mode_t, 0o755)) != 0) {
        const errno_val = std.c.errno(-1);
        if (errno_val != .EXIST) return error.MkdirFailed;
    }
}

/// Open (or create + truncate) a file for writing. Returns the raw fd.
fn openCreateTrunc(dir_path: []const u8, basename: []const u8) !std.c.fd_t {
    const full = try std.fs.path.join(std.heap.page_allocator, &.{ dir_path, basename });
    defer std.heap.page_allocator.free(full);

    return switch (builtin.os.tag) {
        .windows => openCreateTruncWindows(full),
        else => openCreateTruncPosix(full),
    };
}

fn openCreateTruncPosix(full: []const u8) !std.c.fd_t {
    var buf: [8192:0]u8 = undefined;
    const path_z = copyToNull(&buf, full);
    // Posix `open(path, O_WRONLY|O_CREAT|O_TRUNC, 0o644)`. Flags
    // come straight from `std.c.O` (no Windows type-void issues here
    // — Windows is the comptime-else branch).
    const flags: std.c.O = .{
        .ACCMODE = .WRONLY,
        .CREAT = true,
        .TRUNC = true,
        .CLOEXEC = true,
    };
    const rc = std.c.open(path_z, flags, @as(std.c.mode_t, 0o644));
    if (rc < 0) return error.OpenOutFailed;
    return rc;
}

// Win32 CreateFileW + CloseHandle — declared locally because std.os.windows
// 0.16 doesn't expose `kernel32!CreateFileW` or `kernel32!CloseHandle` (the
// std wraps them per-file under different names, e.g. ntdll!ZwCloseHandle for
extern "kernel32" fn CreateFileW(
    lpFileName: [*:0]const u16,
    dwDesiredAccess: std.os.windows.DWORD,
    dwShareMode: std.os.windows.DWORD,
    lpSecurityAttributes: ?*std.os.windows.SECURITY_ATTRIBUTES,
    dwCreationDisposition: std.os.windows.DWORD,
    dwFlagsAndAttributes: std.os.windows.DWORD,
    hTemplateFile: ?std.os.windows.HANDLE,
) callconv(.winapi) ?std.os.windows.HANDLE;

extern "kernel32" fn CloseHandle(hObject: std.os.windows.HANDLE) callconv(.winapi) std.os.windows.BOOL;

// Win32 WriteFile — declared locally because std.os.windows 0.16 doesn't
// expose `kernel32!WriteFile` (the std wraps it under a different name).
// `lpOverlapped` is `LPOVERLAPPED` (a pointer to the OVERLAPPED struct).
extern "kernel32" fn WriteFile(
    hFile: std.os.windows.HANDLE,
    lpBuffer: [*]const u8,
    nNumberOfBytesToWrite: std.os.windows.DWORD,
    lpNumberOfBytesWritten: *std.os.windows.DWORD,
    lpOverlapped: ?*anyopaque,
) callconv(.winapi) std.os.windows.BOOL;

fn closeWindowsHandle(h: std.os.windows.HANDLE) void {
    _ = CloseHandle(h);
}

fn openCreateTruncWindows(full: []const u8) !std.c.fd_t {
    var path_w: [std.fs.max_path_bytes:0]u16 = undefined;
    const written = std.unicode.wtf8ToWtf16Le(&path_w, full) catch
        return error.OpenOutFailed;
    path_w[written] = 0;

    const h_opt = CreateFileW(
        @ptrCast(&path_w),
        0x40000000, // GENERIC_WRITE
        0x1, // FILE_SHARE_READ (so hot-reload windows can read it)
        null,
        2, // CREATE_ALWAYS
        0x80, // FILE_ATTRIBUTE_NORMAL
        null,
    );
    const h = h_opt orelse return error.OpenOutFailed;
    // `std.c.fd_t` is `*anyopaque` on Windows; wrap the HANDLE pointer.
    // lld-link passes the HANDLE through unchanged because both are
    // pointer-sized in x86_64.
    return @ptrFromInt(@intFromPtr(h));
}

/// Windows: open the file via CreateFileW, write `data` via WriteFile, close
/// the handle.
fn writeAllWindows(path: []const u8, data: []const u8) !void {
    var path_w: [std.fs.max_path_bytes:0]u16 = undefined;
    const written = std.unicode.wtf8ToWtf16Le(&path_w, path) catch
        return error.OpenOutFailed;
    path_w[written] = 0;

    const h_opt = CreateFileW(
        @ptrCast(&path_w),
        0x40000000, // GENERIC_WRITE
        0x1, // FILE_SHARE_READ
        null,
        2, // CREATE_ALWAYS
        0x80, // FILE_ATTRIBUTE_NORMAL
        null,
    );
    const h = h_opt orelse return error.OpenOutFailed;
    defer _ = CloseHandle(h);

    // WriteFile can return fewer bytes than requested only on a pipe or async
    // handle.
    var total_written: usize = 0;
    while (total_written < data.len) {
        var chunk_written: std.os.windows.DWORD = 0;
        const ok = WriteFile(
            h,
            data[total_written..].ptr,
            @intCast(data.len - total_written),
            &chunk_written,
            null,
        );
        // `std.os.windows.BOOL` is a typed `c_int`; cast via @intFromEnum
        // for the == 0 comparison (the Bool type doesn't auto-coerce
        // to a bare int).
        if (@intFromEnum(ok) == 0) return error.WriteFailed;
        if (chunk_written == 0) return error.WriteFailed;
        total_written += @intCast(chunk_written);
    }
}

/// Read the entire contents of a file into a fresh allocation. Returns the
/// buffer; caller owns it.
fn readFileAll(allocator: std.mem.Allocator, path: []const u8, max_bytes: usize) ![]u8 {
    return switch (builtin.os.tag) {
        .windows => readFileAllWindows(allocator, path, max_bytes),
        else => readFileAllPosix(allocator, path, max_bytes),
    };
}

fn readFileAllPosix(allocator: std.mem.Allocator, path: []const u8, max_bytes: usize) ![]u8 {
    var path_buf: [8192:0]u8 = undefined;
    const path_z = copyToNull(&path_buf, path);

    const flags: std.c.O = .{ .ACCMODE = .RDONLY, .CLOEXEC = true };
    const fd_rc = std.c.open(path_z, flags, @as(std.c.mode_t, 0));
    if (fd_rc < 0) return error.OpenFileFailed;
    const fd: std.c.fd_t = fd_rc;
    defer _ = std.c.close(fd);

    var buf: std.ArrayList(u8) = .empty;
    defer buf.deinit(allocator);
    try buf.ensureTotalCapacity(allocator, 4 * 1024);
    var total: usize = 0;
    var chunk: [64 * 1024]u8 = undefined;
    while (true) {
        const n_rc = std.c.read(fd, &chunk, chunk.len);
        if (n_rc < 0) return error.ReadFailed;
        const n: usize = @intCast(n_rc);
        if (n == 0) break; // EOF
        if (total + n > max_bytes) return error.FileTooLarge;
        try buf.appendSlice(allocator, chunk[0..n]);
        total += n;
    }
    return buf.toOwnedSlice(allocator);
}

// Windows counterpart — declared locally because std.os.windows 0.16 doesn't
// expose `kernel32!ReadFile` or `kernel32!CloseHandle` (the std wraps them
// per-file under different names).
extern "kernel32" fn ReadFile(
    hFile: std.os.windows.HANDLE,
    lpBuffer: [*]u8,
    nNumberOfBytesToRead: std.os.windows.DWORD,
    lpNumberOfBytesRead: ?*std.os.windows.DWORD,
    lpOverlapped: ?*anyopaque,
) callconv(.winapi) std.os.windows.BOOL;

fn readFileAllWindows(allocator: std.mem.Allocator, path: []const u8, max_bytes: usize) ![]u8 {
    var path_w: [std.fs.max_path_bytes:0]u16 = undefined;
    const written = std.unicode.wtf8ToWtf16Le(&path_w, path) catch
        return error.OpenFileFailed;
    path_w[written] = 0;

    const h_opt = CreateFileW(
        @ptrCast(&path_w),
        0x80000000, // GENERIC_READ
        0x1, // FILE_SHARE_READ
        null,
        3, // OPEN_EXISTING
        0x80, // FILE_ATTRIBUTE_NORMAL
        null,
    );
    const h = h_opt orelse return error.OpenFileFailed;
    defer closeWindowsHandle(h);

    var buf: std.ArrayList(u8) = .empty;
    defer buf.deinit(allocator);
    try buf.ensureTotalCapacity(allocator, 4 * 1024);
    var total: usize = 0;
    var chunk: [64 * 1024]u8 = undefined;
    while (true) {
        var bytes_read: std.os.windows.DWORD = 0;
        const ok = ReadFile(
            h,
            &chunk,
            @intCast(chunk.len),
            &bytes_read,
            null,
        );
        if (ok.toBool() == false) return error.ReadFailed;
        if (bytes_read == 0) break; // EOF
        const n: usize = @intCast(bytes_read);
        if (total + n > max_bytes) return error.FileTooLarge;
        try buf.appendSlice(allocator, chunk[0..n]);
        total += n;
    }
    return buf.toOwnedSlice(allocator);
}

/// MIME type lookup by file extension.
fn inferMime(path: []const u8) []const u8 {
    if (std.mem.endsWith(u8, path, ".html")) return "text/html; charset=utf-8";
    if (std.mem.endsWith(u8, path, ".css")) return "text/css; charset=utf-8";
    if (std.mem.endsWith(u8, path, ".js")) return "application/javascript; charset=utf-8";
    if (std.mem.endsWith(u8, path, ".mjs")) return "application/javascript; charset=utf-8";
    if (std.mem.endsWith(u8, path, ".json")) return "application/json; charset=utf-8";
    if (std.mem.endsWith(u8, path, ".svg")) return "image/svg+xml";
    if (std.mem.endsWith(u8, path, ".png")) return "image/png";
    if (std.mem.endsWith(u8, path, ".jpg") or std.mem.endsWith(u8, path, ".jpeg")) return "image/jpeg";
    if (std.mem.endsWith(u8, path, ".gif")) return "image/gif";
    if (std.mem.endsWith(u8, path, ".webp")) return "image/webp";
    if (std.mem.endsWith(u8, path, ".ico")) return "image/x-icon";
    if (std.mem.endsWith(u8, path, ".woff")) return "font/woff";
    if (std.mem.endsWith(u8, path, ".woff2")) return "font/woff2";
    if (std.mem.endsWith(u8, path, ".ttf")) return "font/ttf";
    if (std.mem.endsWith(u8, path, ".map")) return "application/json; charset=utf-8";
    if (std.mem.endsWith(u8, path, ".txt")) return "text/plain; charset=utf-8";
    return "application/octet-stream";
}
